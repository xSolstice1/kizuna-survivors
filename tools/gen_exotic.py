class Exotic(Icon):
    def __init__(self, palette):
        super().__init__(palette)
        self.glow_c = None
        self.post = []

    def glow(self, c, every=2):
        """After outlining, light empty pixels touching the outline (sparse)."""
        self.glow_c = (c, every)

    def after(self, x, y, c):
        """Pixel painted after the outline pass (e.g. sparkles floating free)."""
        self.post.append((x, y, c))

    def bar(self, x0, y0, x1, y1, w, c):
        dx, dy = x1 - x0, y1 - y0
        ln = math.hypot(dx, dy) or 1
        nx, ny = -dy / ln * w / 2, dx / ln * w / 2
        self.poly([(x0 + nx, y0 + ny), (x1 + nx, y1 + ny), (x1 - nx, y1 - ny), (x0 - nx, y0 - ny)], c)

    def recolor(self, frm, to, pred=lambda x, y: True):
        for y in range(N):
            for x in range(N):
                if self.g[y][x] == frm and pred(x, y):
                    self.g[y][x] = to

    def save(self, name, comment):
        self.outline()
        if self.glow_c:
            c, every = self.glow_c
            ring = [[self.g[y][x] == "K" for x in range(N)] for y in range(N)]
            for y in range(N):
                for x in range(N):
                    if self.g[y][x] == "." and (x + y) % every == 0 and any(
                        0 <= x + dx < N and 0 <= y + dy < N and ring[y + dy][x + dx]
                        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))
                    ):
                        self.g[y][x] = c
        for x, y, c in self.post:
            self.px(x, y, c)
        lines = [f"# {comment} (generated by tools/gen_exotic.py)"]
        lines += [f"{k} {v}" for k, v in self.pal.items()]
        lines += ["---"] + ["".join(r) for r in self.g]
        (OUT / f"{name}.px").write_text("\n".join(lines) + "\n")


def twinkle(i, x, y, c, core):
    i.after(x, y, core)
    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        i.after(x + dx, y + dy, c)


