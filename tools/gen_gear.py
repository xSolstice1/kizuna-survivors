class Gear(Icon):
    def save(self, name, comment):
        self.outline()
        lines = [f"# {comment} (generated by tools/gen_gear.py)"]
        lines += [f"{k} {v}" for k, v in self.pal.items()]
        lines += ["---"] + ["".join(r) for r in self.g]
        (OUT / f"{name}.px").write_text("\n".join(lines) + "\n")


