def sparkle(i, x, y, big, c, core):
    i.px(x, y, core)
    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        i.px(x + dx, y + dy, c)
    if big:
        for dx, dy in ((2, 0), (-2, 0), (0, 2), (0, -2)):
            i.px(x + dx, y + dy, c)


