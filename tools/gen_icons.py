"""Generates 16x16 upgrade icons as .px sources in art/src/icons/.

Shapes are drawn with simple primitives, then every empty pixel touching a
filled one becomes the outline colour. Output is plain .px text, so icons can
still be hand-edited afterwards (re-running this script overwrites them).

    python3 tools/gen_icons.py
"""
import math
import pathlib

N = 16
OUT = pathlib.Path(__file__).resolve().parent.parent / "art/src/icons"


class Icon:
    def __init__(self, palette):
        self.pal = {"K": "#1a1423", **palette}
        self.g = [["."] * N for _ in range(N)]

    def px(self, x, y, c):
        if 0 <= x < N and 0 <= y < N:
            self.g[y][x] = c

    def circle(self, cx, cy, r, c):
        for y in range(N):
            for x in range(N):
                if (x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2 <= r * r:
                    self.g[y][x] = c

    def rect(self, x0, y0, x1, y1, c):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.px(x, y, c)

    def poly(self, pts, c):
        for y in range(N):
            for x in range(N):
                px, py, inside = x + 0.5, y + 0.5, False
                for i in range(len(pts)):
                    (x1, y1), (x2, y2) = pts[i], pts[i - 1]
                    if (y1 > py) != (y2 > py) and px < (x2 - x1) * (py - y1) / (y2 - y1) + x1:
                        inside = not inside
                if inside:
                    self.g[y][x] = c

    def line(self, x0, y0, x1, y1, c):
        steps = int(max(abs(x1 - x0), abs(y1 - y0)) * 2) + 1
        for i in range(steps + 1):
            t = i / steps
            self.px(round(x0 + (x1 - x0) * t), round(y0 + (y1 - y0) * t), c)

    def clear(self, cx, cy, r):
        self.circle(cx, cy, r, ".")

    def outline(self):
        filled = [[self.g[y][x] != "." for x in range(N)] for y in range(N)]
        for y in range(N):
            for x in range(N):
                if not filled[y][x] and any(
                    0 <= x + dx < N and 0 <= y + dy < N and filled[y + dy][x + dx]
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))
                ):
                    self.g[y][x] = "K"

    def save(self, name, comment):
        self.outline()
        lines = [f"# {comment} (generated by tools/gen_icons.py)"]
        lines += [f"{k} {v}" for k, v in self.pal.items()]
        lines += ["---"] + ["".join(r) for r in self.g]
        (OUT / f"{name}.px").write_text("\n".join(lines) + "\n")


def star_points(cx, cy, r_out, r_in, n=5, rot=-math.pi / 2):
    pts = []
    for i in range(n * 2):
        r = r_out if i % 2 == 0 else r_in
        a = rot + i * math.pi / n
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


