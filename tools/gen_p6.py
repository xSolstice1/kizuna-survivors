sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from gen_w1 import C as W1Canvas  # noqa: E402

SRC = pathlib.Path(__file__).resolve().parent.parent / "art/src"


class C(W1Canvas):
    def save(self, path, comment):
        self.outline()
        lines = [f"# {comment} (generated by tools/gen_p6.py)"]
        lines += [f"{k} {v}" for k, v in self.pal.items()]
        lines += ["---"] + ["".join(r) for r in self.g]
        (SRC / f"{path}.px").write_text("\n".join(lines) + "\n")


