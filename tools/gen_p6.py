"""Generates the phase-6 newcomers (two Uncommons and a Leader per world) as .px sources.

    python3 tools/gen_p6.py

Shotengai's trio goes to art/src/<key>.px (beside wisp.px); each world's to
art/src/w<n>/{uncommon_a,uncommon_b,leader}.px. Uncommons are 24x24, Leaders 32x32.
tools/hd/enemies_p6.py redraws each one in HD. Deterministic.
"""
import math
