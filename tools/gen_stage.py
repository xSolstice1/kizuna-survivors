"""Generates stage 1 (Neon Shotengai) tiles and props as .px sources in art/src/stage/.

    python3 tools/gen_stage.py

Deterministic (seeded), so re-running produces identical files.
"""
import pathlib
import random

OUT = pathlib.Path(__file__).resolve().parent.parent / "art/src/stage"
rng = random.Random(7)


class Canvas:
    def __init__(self, w, h, palette):
        self.w, self.h = w, h
        self.pal = {"K": "#1a1423", **palette}
        self.g = [["."] * w for _ in range(h)]

    def px(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.g[y][x] = c

    def rect(self, x0, y0, x1, y1, c):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.px(x, y, c)

    def ellipse(self, cx, cy, rx, ry, c):
        for y in range(self.h):
            for x in range(self.w):
                if ((x + 0.5 - cx) / rx) ** 2 + ((y + 0.5 - cy) / ry) ** 2 <= 1:
                    self.g[y][x] = c

    def outline(self):
        filled = [[self.g[y][x] != "." for x in range(self.w)] for y in range(self.h)]
        for y in range(self.h):
            for x in range(self.w):
                if not filled[y][x] and any(
                    0 <= x + dx < self.w and 0 <= y + dy < self.h and filled[y + dy][x + dx]
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))
                ):
                    self.g[y][x] = "K"

    def save(self, name, comment, outline=False):
        if outline:
            self.outline()
        lines = [f"# {comment} (generated by tools/gen_stage.py)"]
        lines += [f"{k} {v}" for k, v in self.pal.items()]
        lines += ["---"] + ["".join(r) for r in self.g]
        (OUT / f"{name}.px").write_text("\n".join(lines) + "\n")


STONE = {"A": "#2b2840", "B": "#312d49", "C": "#27243a", "M": "#1c1a2b", "H": "#3a3654"}


def paving(c):
    """Offset rows of 8x8 stones with mortar lines and the odd highlight."""
    for row in range(4):
        off = 4 if row % 2 else 0
        for col in range(-1, 5):
            x0, y0 = col * 8 + off, row * 8
            tone = rng.choice("AABBC")
            c.rect(x0, y0, x0 + 7, y0 + 7, tone)
            c.rect(x0, y0 + 7, x0 + 7, y0 + 7, "M")
            c.rect(x0 + 7, y0, x0 + 7, y0 + 7, "M")
            if rng.random() < 0.5:
                c.px(x0 + 1, y0 + 1, "H")
            if rng.random() < 0.15:  # crack
                x, y = x0 + rng.randint(2, 5), y0 + rng.randint(2, 5)
                for _ in range(3):
                    c.px(x, y, "M")
                    x, y = x + rng.choice((-1, 0, 1)), y + 1


def main():
    OUT.mkdir(parents=True, exist_ok=True)

    for name in ("paving_a", "paving_b"):
        c = Canvas(32, 32, STONE)
        paving(c)
        c.save(name, "Paving stones")

    c = Canvas(32, 32, {**STONE, "Y": "#7a6a2a", "y": "#5a4e20"})
    paving(c)
    c.rect(12, 0, 19, 31, "Y")
    for y in range(1, 32, 4):
        for x in range(13, 19, 3):
            c.px(x, y, "y")
            c.px(x + 1, y, "y")
    c.save("tactile", "Yellow tactile paving strip")

    c = Canvas(32, 32, {**STONE, "D": "#1f2030", "d": "#2a2b3d", "R": "#3a3b52"})
    paving(c)
    c.ellipse(16, 16, 11, 11, "R")
    c.ellipse(16, 16, 10, 10, "D")
    for k in range(-8, 9, 4):
        c.rect(16 + k, 8, 16 + k, 24, "d")
    c.rect(8, 15, 24, 16, "d")
    c.save("manhole", "Manhole cover")

    c = Canvas(32, 32, {**STONE, "W": "#1d2440", "P": "#ff5aa8", "Q": "#5ad8ff"})
    paving(c)
    c.ellipse(16, 18, 12, 7, "W")
    for x in range(9, 14):
        c.px(x, 16, "P")
    for x in range(17, 21):
        c.px(x, 20, "Q")
    c.save("puddle", "Puddle reflecting neon")

    # ── Props ──
    c = Canvas(12, 18, {"R": "#d8433a", "r": "#9c2a2a", "Y": "#ffd27a", "B": "#2a1a1a"})
    c.rect(5, 0, 6, 2, "B")
    c.rect(2, 3, 9, 4, "B")
    c.ellipse(6, 9.5, 5.5, 6, "R")
    for y in (6, 9, 12):
        c.rect(1, y, 10, y, "r")
    c.rect(4, 7, 7, 11, "Y")
    c.rect(2, 15, 9, 16, "B")
    c.save("lantern", "Red paper lantern (chochin)", outline=True)

    c = Canvas(16, 28, {"B": "#2f5fd0", "b": "#1d3a8a", "W": "#e8f4ff", "L": "#9fe8ff", "G": "#3a3a4a", "R": "#ff5a6a", "Y": "#ffe066"})
    c.rect(0, 0, 15, 27, "B")
    c.rect(0, 0, 15, 2, "b")
    c.rect(2, 4, 13, 14, "W")
    for row in range(3):
        for col in range(4):
            c.rect(3 + col * 3, 5 + row * 3, 4 + col * 3, 6 + row * 3, rng.choice("RLY"))
    c.rect(2, 16, 9, 18, "L")
    c.rect(11, 16, 13, 21, "G")
    c.rect(2, 22, 13, 25, "G")
    c.save("vending", "Vending machine", outline=True)

    c = Canvas(32, 24, {"R": "#d8433a", "W": "#f2e6d0", "T": "#8a5a3a", "t": "#5a3a24", "Y": "#ffd23a", "G": "#6be0a0"})
    for x in range(32):
        col = "R" if (x // 4) % 2 == 0 else "W"
        c.rect(x, 0, x, 6, col)
    for x in range(0, 32, 4):
        c.rect(x + 1, 7, x + 2, 8, "R" if (x // 4) % 2 == 0 else "W")
    c.rect(1, 9, 2, 23, "T")
    c.rect(29, 9, 30, 23, "T")
    c.rect(1, 15, 30, 18, "T")
    c.rect(1, 18, 30, 19, "t")
    for x in range(4, 28, 5):
        c.ellipse(x + 2, 13.5, 2, 1.6, rng.choice("YG"))
    c.save("stall", "Festival food stall", outline=True)

    c = Canvas(26, 10, {"P": "#ff5aa8", "p": "#c02a78", "C": "#5ad8ff", "F": "#2a1a3a"})
    c.rect(0, 0, 25, 9, "F")
    c.rect(1, 1, 24, 1, "p")
    c.rect(1, 8, 24, 8, "p")
    # abstract glyphs
    for k, x in enumerate((3, 9, 15, 20)):
        col = "P" if k % 2 == 0 else "C"
        c.rect(x, 3, x + 3, 3, col)
        c.rect(x + 1, 4, x + 1, 6, col)
        c.rect(x, 6, x + 3, 6, col)
    c.save("neon_sign", "Neon sign", outline=True)

    c = Canvas(14, 12, {"T": "#9a6a3a", "t": "#6a4424", "L": "#c08a52"})
    c.rect(0, 4, 13, 11, "T")
    c.rect(3, 0, 10, 4, "L")
    c.rect(0, 7, 13, 7, "t")
    c.rect(6, 4, 7, 11, "t")
    c.save("crates", "Stacked crates", outline=True)

    print("wrote", len(list(OUT.glob("*.px"))), "stage sprites to", OUT)


if __name__ == "__main__":
    main()
